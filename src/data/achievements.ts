/**
 * Märken. Varje märke har en riktig predikatfunktion som körs mot spelarens
 * faktiska statistik - inga fejkade eller dekorativa villkor.
 */

const questsAtLeast =
  (count: number) =>
  (ctx: AchievementContext): boolean =>
    ctx.statistics.questsCompleted >= count;

const streakAtLeast =
  (days: number) =>
  (ctx: AchievementContext): boolean =>
    ctx.streak.longest >= days;

const categoryAtLeast =
  (category: string, count: number) =>
  (ctx: AchievementContext): boolean =>
    (ctx.statistics.questsByCategory[category] ?? 0) >= count;

