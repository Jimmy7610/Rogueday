import type { ActivityPack } from '@/types';

/**
 * Activity packs — curated situation modes.
 *
 * A pack is a declaration, not a container. It owns no quests: it describes a
 * situation ("I am completely done in", "it is raining", "get me out of the
 * house") as a set of hard constraints plus soft preferences over the library
 * that already exists.
 *
 * The split matters:
 *
 *   HARD  allowedDurations / allowedEnergies / allowedLocations /
 *         requiredTags / excludedTags / excludedCategories / onlyCategories
 *         A quest outside these is never offered by this pack. Ever.
 *
 *   SOFT  preferredEnergy / preferredMoods / preferredTags /
 *         preferredCategories
 *         These only reweight an already-legal pool, so a pack can lean
 *         somewhere without ever emptying itself.
 *
 * Nothing here reads the clock, the weather, or the network. REGNIG DAG and
 * SÖNDAGSRESET are hand-picked moods, not detected conditions — the copy says
 * so, and the code has no way to detect either.
 */

